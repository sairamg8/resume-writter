  let any = false;
  for (const n of canvasList) if (new RegExp('\\b' + n + '\\b').test(bd)) { named.add(n); any = true; }
  for (const t of bd.match(/\b(?:Mobile|Editor|Project|Jobs)[A-Za-z]*\b/g) || []) if (!canvasList.includes(t)) unknownBoards.push(`${b.id}: ${t}`);
