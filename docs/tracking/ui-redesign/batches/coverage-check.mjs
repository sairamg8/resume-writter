P();
for (const f of FILES) P(`- ${f}: ${catchAll[f] ? 'catch-all -> ' + catchAll[f] : 'NO CATCH-ALL RULE'}`);
P();
const noOwner = [], multi = [], viaCatch = {};
for (const f of FILES) {
  for (const id of distinct[f]) {
    const k = `${f}:${id}`; const o = owners.get(k) || [];
    if (!o.length) { if (catchAll[f]) (viaCatch[f] ||= []).push(id); else noOwner.push(k); }
    if (o.length > 1) multi.push(`${k} -> ${o.join(' + ')}`);
  }
}
P('## 2. Rows owned by NO batch (not listed and no catch-all rule for the file)');
P(noOwner.length ? noOwner.map(x => '- ' + x).join('\n') : '- none (every file has a catch-all)');
P();
P('## 3. Rows owned by MORE than one batch (explicit listings)');
P(multi.length ? multi.map(x => '- ' + x).join('\n') : '- none');
P();
P('## 4. Ranges / items that match no rows, and ranges with gaps');
P(rangeIssues.length ? rangeIssues.map(x => '- ' + x).join('\n') : '- none');
if (badItems.length) { P(); P('Unparseable ownership items:'); badItems.forEach(x => P('- ' + x)); }
P();
P('## 5. Rows that reach their batch ONLY through the catch-all rule (not listed by ID)');
P();
P('These are owned (no fall-through) but no batch lists them; a reviewer should confirm the catch-all batch is the right home.');
P();
for (const f of FILES) {
  const ids = (viaCatch[f] || []).sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));
  P(`### ${f} -> ${catchAll[f]}: ${ids.length} row(s)`);
  for (const id of ids) {
    const r = byKey.get(`${f}:${id}`)[0];
    P(`- ${id} [${r.status || (r.drawn ? 'drawn' : '')}] (${r.section}) ${r.text.slice(0, 80)}`);
  }
  P();
}

// ---------- 6. CHANGED / MISSING ----------
P('## 6. CHANGED / MISSING rows: owner and fix text');
P();
const cm = [];
for (const f of FILES) for (const r of rows[f]) {
  if (r.revised || r.drawn) continue;
  if (!/^(CHANGED|MISSING)/i.test(r.status)) continue;
  const o = owners.get(key(r)) || (catchAll[f] ? [catchAll[f] + ' (catch-all)'] : []);
  cm.push({ r, o });
}
const noFix = cm.filter(x => !x.r.fix || x.r.fix.length < 8);
P(`Total CHANGED/MISSING rows: ${cm.length}. With an owner: ${cm.filter(x => x.o.length).length}. Without any owner: ${cm.filter(x => !x.o.length).length}. With an empty/very short Fix cell: ${noFix.length}.`);
P();
P('Rows with an empty or very short Fix cell:');
P(noFix.length ? noFix.map(x => `- ${key(x.r)} [${x.r.status}] -> ${x.o.join(' + ')} :: "${x.r.fix}"`).join('\n') : '- none');
P();
P('CHANGED/MISSING rows that depend on a catch-all rule (owner shown):');
const viaC = cm.filter(x => (x.o[0] || '').includes('catch-all'));
P(viaC.length ? viaC.map(x => `- ${key(x.r)} [${x.r.status}] -> ${x.o[0]} (${x.r.section}) ${x.r.text.slice(0, 70)}`).join('\n') : '- none');
P();
P('Per batch: explicit rows, catch-all rows, CHANGED, MISSING');
P();
P('| batch | explicit rows | catch-all rows | CHANGED | MISSING |');
P('|---|---|---|---|---|');
for (const b of plan.batches) {
  let ex = 0, ca = 0, ch = 0, mi = 0;
  for (const f of FILES) for (const id of distinct[f]) {
    const k = `${f}:${id}`; const o = owners.get(k) || [];
    const own = o.length ? o : (catchAll[f] ? [catchAll[f]] : []);
    if (!own.includes(b.id)) continue;
    if (o.includes(b.id)) ex++; else ca++;
    const r = byKey.get(k).find(x => !x.revised && !x.drawn);
    if (r && /^CHANGED/i.test(r.status)) ch++;
    if (r && /^MISSING/i.test(r.status)) mi++;
  }
  P(`| ${b.id} | ${ex} | ${ca} | ${ch} | ${mi} |`);
}
P();

// ---------- 7. DRAWN BUT NOT vs parked ----------
P('## 7. "DRAWN BUT NOT IN THE LIVE APP" items vs the plan\'s parked lists');
P();
const parkedBlob = (plan.batches.flatMap(b => b.parked || []).concat(plan.parkedForOwner || [])).join('\n');
const parkedIdMentions = new Set(parkedBlob.match(/\b(?:[A-Z]+-\d+|N\d+)\b/g) || []);
const isPark = h => /\bPARK/i.test(h);
const drawnItems = [];
for (const f of FILES) {
  const seen = new Set();
  for (const r of rows[f]) {
    if (!r.drawn || seen.has(r.id)) continue; seen.add(r.id);
    drawnItems.push({ r, handling: rows[f].filter(x => x.id === r.id && x.drawn).map(x => x.handling).join(' ') });
  }
}
let parkN = 0, kept = 0;
const unmentioned = [];
for (const { r, handling } of drawnItems) {
  const own = owners.get(key(r)) || (catchAll[r.file] ? [catchAll[r.file] + '*'] : []);
  if (isPark(handling)) { parkN++; if (!parkedIdMentions.has(r.id)) unmentioned.push({ r, own, handling }); } else kept++;
}
P(`Drawn-but-not items: ${drawnItems.length} distinct (${parkN} with handling PARK, ${kept} other: same function / display-only / kept). PARK items whose ID is not cited in any batch "parked" list or parkedForOwner (IDs are matched area-agnostically, so a hit is a loose match): ${unmentioned.length}.`);
P();
P('PARK items with no ID citation in the plan (judge against the parkedForOwner prose):');
P();
for (const u of unmentioned) P(`- ${key(u.r)} -> owner ${u.own.join('+') || 'NONE'} :: ${u.r.text.slice(0, 110).replace(/\n/g, ' ')} || ${u.handling.slice(0, 90)}`);
P();
const dn = drawnItems.filter(x => !(owners.get(key(x.r)) || []).length && !catchAll[x.r.file]);
P('Drawn items owned by NO batch: ' + (dn.length ? dn.map(x => key(x.r)).join(', ') : 'none'));
const dc = drawnItems.filter(x => !(owners.get(key(x.r)) || []).length && catchAll[x.r.file]);
P('Drawn items reached only via a catch-all rule: ' + (dc.length ? dc.map(x => key(x.r)).join(', ') : 'none'));
P();

// ---------- 8. test files ----------
P('## 8. Test files named in testsToUpdate');
P();
const walk = (d, acc = []) => { if (!fs.existsSync(d)) return acc; for (const e of fs.readdirSync(d, { withFileTypes: true })) { if (e.name === 'node_modules' || e.name.startsWith('.')) continue; const p = path.join(d, e.name); if (e.isDirectory()) walk(p, acc); else acc.push(path.relative(ROOT, p)); } return acc; };
const allFiles = [...walk(path.join(ROOT, 'tests')), ...walk(path.join(ROOT, 'cypress'))];
const baseOf = p => path.basename(p).replace(/\.(test|spec|unit|cy)?\.?(mjs|js)$/, '');
const tokens = [];
for (const b of plan.batches) for (const item of b.testsToUpdate || []) {
  let mode = '';
  for (const raw of item.split(/[,;()\s]+/)) {
    const t = raw.replace(/^[.:]+|[.:]+$/g, '');
    if (!t) continue;
    if (/^cypress$/i.test(t)) { mode = 'cy'; continue; }
    if (/^playwright$/i.test(t)) { mode = 'pw'; continue; }
    if (/^(tests|src|cypress)\//.test(t)) { tokens.push({ b: b.id, t, mode: '' }); continue; }
    if (/^\d{1,3}[a-z]?-[\w*.-]+$/.test(t) || /^(r4cl|r4dsn|r5hunt\d*|imp|r5)-[\w*.-]+$/.test(t) || /\.(mjs|js)$/.test(t)) { tokens.push({ b: b.id, t, mode }); continue; }
    if (/^\d{2,3}$/.test(t)) { tokens.push({ b: b.id, t, mode: mode || 'num' }); continue; }
    if (mode === 'pw' && /^[a-z][\w-]+$/.test(t) && /(-|^picker$)/.test(t) && !/^(only|opener|the|and|stays|stay|must|green)$/.test(t)) tokens.push({ b: b.id, t, mode });
  }
}
const unresolved = []; let resolved = 0;
for (const { b, t, mode } of tokens) {
  const tt = t.replace(/\*+/g, '');
  let hits;
  if (/^(tests|cypress)\//.test(t)) hits = allFiles.filter(f => f.startsWith(tt.replace(/\.(mjs|js)$/, '')) || f === tt);
  else if (mode === 'pw') hits = allFiles.filter(f => f.startsWith('tests/playwright/') && baseOf(f).startsWith(tt));
  else if (mode === 'cy') hits = allFiles.filter(f => f.startsWith('cypress/e2e/') && path.basename(f).startsWith(tt + (/^\d+$/.test(tt) ? '-' : '')));
  else if (mode === 'num') hits = allFiles.filter(f => (f.startsWith('tests/pdf/') || f.startsWith('cypress/e2e/')) && path.basename(f).startsWith(tt + '-'));
  else hits = allFiles.filter(f => path.basename(f).startsWith(tt));
  if (!hits.length) unresolved.push(`${b}: ${t}${mode ? ' [' + mode + ']' : ''}`); else resolved++;
}
P(`Tokens parsed: ${tokens.length}; resolved to at least one existing file: ${resolved}; unresolved: ${unresolved.length}.`);
P();
P('Unresolved (no existing file starts with the name):');
P(unresolved.length ? unresolved.map(x => '- ' + x).join('\n') : '- none');
P();

