const readme = fs.readFileSync(path.join(UI, 'README.md'), 'utf8');
const sec = readme.split('## On the canvas')[1].split('## Product calls')[0];
const canvasList = ['Main','New','Editor','EditorSection','EditorLetter','EditorAts','Jobs','MobileHome','MobileEdit','MobilePreview','MobileDesign','Paper','Letter','EditorPersonal','EditorDownload','EditorShare','EditorTemplates','EditorImprove','EditorDraft','JobsList','JobAdd','JobsInsights','MobileJobs','Projects','ProjectBoard','ProjectList','ProjectIssue','ProjectSettings','ProjectCalendar','ProjectTimeline','ProjectSummary','ProjectBacklog','MobileProject','ShellMenus','Empty','ImportModal','Public','Legal','States'];
