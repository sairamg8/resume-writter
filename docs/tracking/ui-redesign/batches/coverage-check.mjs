// Coverage check of the UI-rebuild plan against the parity files.
// Usage (from the worktree root): node docs/tracking/ui-redesign/batches/coverage-check.mjs docs/tracking/ui-redesign docs/tracking/ui-redesign/plan-work/final.json . docs/tracking/ui-redesign/batches/coverage-check.md
// <plan json> = the final plan JSON (plan-work/final.json). A hand-written coverage-findings.md next to the report is prepended.
// Mechanical only: reads the 7 parity files, the plan JSON and the test tree; writes the report. Runs no tests.
import fs from 'node:fs';
import path from 'node:path';

const [,, UI, PLAN, ROOT, OUT] = process.argv;
const rawPlan = JSON.parse(fs.readFileSync(PLAN, 'utf8'));
const plan = rawPlan.plan || rawPlan; // plan-work/final.json holds {plan, rejected, coverageClean}
const FILES = ['applications','editor-content','editor-design-templates','editor-letter-ats-export','mobile','projects','shell-docs'];
const out = [];
const P = (s='') => out.push(s);

// ---------- 1. extract rows ----------
const splitRow = l => l.replace(/^\s*\|/, '').replace(/\|\s*$/, '').split(/(?<!\\)\|/).map(c => c.trim());
const idRe = /(?:[A-Z]+-\d+|\bN\d+)\b/g;
const rows = {};
for (const f of FILES) {
  const lines = fs.readFileSync(path.join(UI, 'parity', f + '.md'), 'utf8').split('\n');
  let h2 = '', h3 = '', header = null; const list = [];
  lines.forEach((l, i) => {
    if (/^## /.test(l)) { h2 = l; h3 = ''; header = null; return; }
    if (/^### /.test(l)) { h3 = l; header = null; return; }
    if (!/^\s*\|/.test(l)) return;
    const cells = splitRow(l);
    if (/^[-: ]+$/.test(cells[0])) return;
    if (['ID', '#', 'File'].includes(cells[0])) { header = cells; return; }
    if (!header || header[0] === 'File') return;
    const ids = cells[0].match(idRe);
    if (!ids) return;
    const sec = (h2 + ' ' + h3);
    const drawn = /DRAWN BUT NOT/i.test(sec) || /^(What the canvas draws|Drawn control|Canvas draws|Board \+ element)/i.test(header[1] || '');
    const si = header.findIndex(c => /^Status$/i.test(c));
    const fi = header.findIndex(c => /^Fix/i.test(c));
    const hi = header.findIndex(c => /^(Recommended handling|Handling)/i.test(c));
    const revised = /revised/i.test(cells[0]);
    for (const id of ids) {
      const m = id.match(/^([A-Z]+)-?(\d+)$/);
      list.push({ file: f, id, prefix: m[1], num: +m[2], section: sec.replace(/#+ /g, '').trim().slice(0, 70), drawn, revised,
        status: si >= 0 ? (cells[si] || '').trim() : '', fix: fi >= 0 ? cells[fi] || '' : '', handling: hi >= 0 ? cells[hi] || '' : '', text: header[0] === '#' ? ((cells[1] || '') + ' ' + (cells[2] || '')) : (cells[1] || ''), line: i + 1 });
    }
  });
  rows[f] = list;
}
const key = r => `${r.file}:${r.id}`;
const byKey = new Map();
for (const f of FILES) for (const r of rows[f]) { if (!byKey.has(key(r))) byKey.set(key(r), []); byKey.get(key(r)).push(r); }

P('# Coverage check of the UI-rebuild plan against the parity files');
P();
P('Generated by coverage-check.mjs (mechanical: reads the 7 parity files, plan-work/final.json and the test tree; runs no tests).');
P();
P('## 0. Row inventory');
P();
P('| file | distinct row IDs | table rows incl. revised duplicates | drawn-but-not IDs | CHANGED | MISSING |');
P('|---|---|---|---|---|---|');
const distinct = {};
for (const f of FILES) {
  const ids = new Set(rows[f].map(r => r.id));
  distinct[f] = ids;
  const st = s => rows[f].filter(r => !r.revised && !r.drawn && new RegExp('^' + s, 'i').test(r.status)).length;
  P(`| ${f} | ${ids.size} | ${rows[f].length} | ${new Set(rows[f].filter(r => r.drawn).map(r => r.id)).size} | ${st('CHANGED')} | ${st('MISSING')} |`);
}
P();
const dups = [];
for (const [k, v] of byKey) { const real = v.filter(r => !r.revised); if (real.length > 1) dups.push(`${k} (lines ${real.map(r => r.line).join(', ')})`); }
P('### Duplicate row IDs inside one file (excluding "(revised)" rows)');
P(dups.length ? dups.map(d => '- ' + d).join('\n') : '- none');
P();

// ---------- 2. parse ownership ----------
const owners = new Map();
const catchAll = {};
const badItems = [];
const rangeIssues = [];
function addOwner(k, b) { if (!owners.has(k)) owners.set(k, []); if (!owners.get(k).includes(b)) owners.get(k).push(b); }
for (const b of plan.batches) {
  for (const entry of b.parityOwned || []) {
    const m = entry.match(/^([a-z-]+):\s*(.*)$/s);
    if (!m || !FILES.includes(m[1])) { badItems.push(`${b.id}: cannot read file prefix of "${entry.slice(0, 60)}"`); continue; }
    const f = m[1];
    let body = m[2];
    if (/CATCH-ALL/.test(body)) {
      const cm = body.match(/belongs to (B\d+[a-z]?)/);
      if (cm) catchAll[f] = cm[1]; else badItems.push(`${b.id}: catch-all without batch in ${f}`);
      continue;
    }
    body = body.replace(/\([^)]*\)/g, '');
    for (const item of body.split(',').map(s => s.trim()).filter(Boolean)) {
      const r = item.match(/^([A-Z]+-?)(\d+)(?:\.\.([A-Z]+-?)(\d+))?$/);
      if (!r) { badItems.push(`${b.id} ${f}: unreadable item "${item}"`); continue; }
      const [, p1, n1, p2, n2] = r;
      const pre = p1.replace(/-$/, '');
      if (p2 && p2.replace(/-$/, '') !== pre) { badItems.push(`${b.id} ${f}: range "${item}" mixes prefixes`); continue; }
      const lo = +n1, hi = n2 ? +n2 : +n1;
      const matched = rows[f].filter(x => x.prefix === pre && x.num >= lo && x.num <= hi);
      const nums = new Set(matched.map(x => x.num));
      if (!nums.size) rangeIssues.push(`${b.id} ${f}: "${item}" matches NO rows`);
      else {
        const gaps = []; for (let n = lo; n <= hi; n++) if (!nums.has(n)) gaps.push(n);
        if (gaps.length) rangeIssues.push(`${b.id} ${f}: "${item}" has ${gaps.length} number(s) with no row (${gaps.slice(0, 12).join(',')}${gaps.length > 12 ? ',...' : ''})`);
      }
      for (const id of new Set(matched.map(x => x.id))) addOwner(`${f}:${id}`, b.id);
    }
  }
}

// ---------- 3. ownership report ----------
