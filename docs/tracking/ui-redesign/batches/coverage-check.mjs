// 10c. drawn-but-not: strict citation (batch that owns the row cites it in ITS parked list, ranges and slashes expanded)
P('### 10c. PARK-handled drawn items: is the OWNING batch\'s `parked` list citing it? (ranges and A/B slashes expanded)');
const expand = s => {
  const set = new Set();
  for (const m of s.matchAll(/\b([A-Z]+)-?(\d+)(?:\.\.(?:[A-Z]+-?)?(\d+)|((?:\/\d+)+))?/g)) {
    const pre = m[1]; const lo = +m[2];
    if (m[3]) for (let n = lo; n <= +m[3]; n++) set.add(pre + ':' + n);
    else if (m[4]) { set.add(pre + ':' + lo); m[4].split('/').filter(Boolean).forEach(n => set.add(pre + ':' + +n)); }
    else set.add(pre + ':' + lo);
  }
  return set;
};
const parkedBy = {}; for (const b of plan.batches) parkedBy[b.id] = expand((b.parked || []).join('\n'));
const parkedAll = expand(parkedBlob);
const weak = [];
for (const { r, handling } of drawnItems) {
  if (!isPark(handling)) continue;
  const o = owners.get(key(r)) || [];
  const idk = r.prefix + ':' + r.num;
  if (o.some(b => parkedBy[b].has(idk))) continue;
  weak.push({ r, o, anywhere: parkedAll.has(idk) });
}
P(`PARK items not cited by their owning batch's parked list: ${weak.length}.`);
for (const w of weak) P(`- ${key(w.r)} -> owner ${w.o.join('+') || '(none)'}${w.anywhere ? ' [cited in ANOTHER batch parked list]' : ' [not cited by ID anywhere]'} :: ${w.r.text.slice(0, 100).replace(/\n/g, ' ')}`);
